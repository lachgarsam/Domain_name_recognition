import torch
import logging
from typing import Dict, Any, Optional
from transformers.integrations import MLflowCallback

from transformers import (
    AutoModelForCausalLM,
    AutoTokenizer,
    TrainingArguments,
    BitsAndBytesConfig,
    PreTrainedModel,
    PreTrainedTokenizer,
)
from peft import PeftConfig
from trl import SFTTrainer
from datasets import Dataset

# Imports from our own project
from data_processing import load_and_prepare_dataset
from utils import get_device
from tuning_strategies import get_tuning_strategy, TuningStrategy, QLoRAStrategy

logger = logging.getLogger(__name__)


class FineTuner:
    """
    Encapsulates the entire fine-tuning process of a LLM.

    This class is model- and fine-tuning-method-agnostic. It uses
    the Strategy Design Pattern to delegate specific logic of each
    technique (LoRA, QLoRA, etc.) to dedicated strategy classes.
    The whole process is controlled via a single configuration dictionary.

    Attributes:
        config (Dict[str, Any]): The full experiment configuration.
        device (str): Detected compute device ('mps', 'cuda', 'cpu').
        strategy (TuningStrategy): Strategy object for the chosen tuning technique.
        model (PreTrainedModel): The base model, potentially modified by the strategy.
        tokenizer (PreTrainedTokenizer): The tokenizer associated with the model.
        dataset (Dataset): The dataset prepared for training.
        peft_config (Optional[PeftConfig]): The PEFT config generated by the strategy.
        trainer (SFTTrainer): The TRL Trainer object, initialized after calling .tune().
    """

    def __init__(self, config: Dict[str, Any]):
        """
        Initialize the FineTuner by loading and configuring all components.
        """
        logger.info("Initializing FineTuner...")
        self.config: Dict[str, Any] = config
        self.device: str = get_device()
        self.trainer: Optional[SFTTrainer] = None

        # Select the tuning strategy from the configuration
        self.strategy: TuningStrategy = get_tuning_strategy(config)

        # Load the core components
        self._load_and_prepare_data()
        self._load_model_and_tokenizer()

        # Prepare the model for tuning using the chosen strategy
        self._prepare_model_for_tuning()
        logger.info("FineTuner initialized successfully.")

    def _load_model_and_tokenizer(self):
        """Load the base model and its tokenizer, applying quantization if needed."""
        model_name = self.config["model"]["base_model_name"]
        logger.info(f"Loading base model '{model_name}'")

        quantization_config = None
        # QLoRA strategy is the only one requiring quantization on load
        if isinstance(self.strategy, QLoRAStrategy):
            logger.info(
                "QLoRA strategy detected. Applying 4-bit quantization during model load."
            )
            q_conf = self.strategy.config["quantization"]
            quantization_config = BitsAndBytesConfig(
                load_in_4bit=q_conf["load_in_4bit"],
                bnb_4bit_quant_type=q_conf["bnb_4bit_quant_type"],
                bnb_4bit_use_double_quant=q_conf["bnb_4bit_use_double_quant"],
                bnb_4bit_compute_dtype=getattr(torch, q_conf["bnb_4bit_compute_dtype"]),
            )

        self.model: PreTrainedModel = AutoModelForCausalLM.from_pretrained(
            model_name,
            quantization_config=quantization_config,
            device_map="auto" if quantization_config else None,
            trust_remote_code=self.config["model"].get("trust_remote_code", True),
        )
        self.tokenizer: PreTrainedTokenizer = AutoTokenizer.from_pretrained(model_name)

        if self.tokenizer.pad_token is None:
            logger.info("Tokenizer missing pad token. Setting pad_token to eos_token.")
            self.tokenizer.pad_token = self.tokenizer.eos_token

        if self.tokenizer.chat_template is None:
            self._apply_default_chat_template(model_name)

    def _apply_default_chat_template(self, model_name: str):
        """Apply a default chat template if it is missing in the tokenizer."""
        logger.warning(
            f"Tokenizer for {model_name} is missing a chat template. Applying a default."
        )
        template = (
            "{% for message in messages %}"
            "{% if message['role'] == 'user' %}"
            "{{'<|user|>\\n' + message['content'] + '<|end|>\\n'}}"
            "{% elif message['role'] == 'assistant' or message['role'] == 'model' %}"
            "{{'<|assistant|>\\n' + message['content'] + '<|end|>\\n'}}"
            "{% endif %}"
            "{% endfor %}"
            "{% if add_generation_prompt %}"
            "{{'<|assistant|>\\n'}}"
            "{% endif %}"
        )
        self.tokenizer.chat_template = template

    def _load_and_prepare_data(self):
        """Load and prepare the dataset for conversational format."""
        logger.info("Loading and preparing dataset...")
        self.dataset: Dataset = load_and_prepare_dataset(self.config)

    def _prepare_model_for_tuning(self):
        """Delegate model preparation and PEFT config to the chosen strategy."""
        logger.info(
            f"Preparing model with strategy: {self.strategy.__class__.__name__}"
        )
        self.model = self.strategy.prepare_model(self.model)
        self.peft_config: Optional[PeftConfig] = self.strategy.get_peft_config()

        # Manual device placement needed only if device_map is not used (e.g., non-QLoRA)
        if not isinstance(self.strategy, QLoRAStrategy):
            precision = self.config["training"].get("precision")
            if precision == "bf16" and self.device == "mps":
                logger.info("Manually casting model to bfloat16 for MPS device.")
                self.model = self.model.to(torch.bfloat16)
            self.model.to(self.device)

    def tune(self):
        """
        Configure and launch the training process using SFTTrainer.
        """
        train_conf = self.config["training"]

        bf16_enabled = train_conf.get("precision") == "bf16"
        # Disable bf16 flag for Trainer on MPS to avoid erroneous check
        if self.device == "mps":
            bf16_enabled = False

        training_args = TrainingArguments(
            output_dir=train_conf["output_dir"],
            report_to="mlflow",
            per_device_train_batch_size=train_conf.get(
                "per_device_train_batch_size", 4
            ),
            gradient_accumulation_steps=train_conf.get(
                "gradient_accumulation_steps", 1
            ),
            learning_rate=train_conf.get("learning_rate", 2e-5),
            num_train_epochs=train_conf.get("num_train_epochs", 3),
            logging_strategy=train_conf.get("logging_strategy", "epoch"),
            eval_steps=train_conf["eval_steps"],
            metric_for_best_model=train_conf.get("metric_for_best_model", "eval_loss"),
            bf16=bf16_enabled,
            fp16=(train_conf.get("precision") == "fp16"),
            max_grad_norm=train_conf.get("max_grad_norm", 1.0),
            warmup_ratio=train_conf.get("warmup_ratio", 0.03),
            lr_scheduler_type=train_conf.get("lr_scheduler_type", "cosine"),
            weight_decay=train_conf.get("weight_decay", 0),
        )

        splits = self.dataset.train_test_split(
            test_size=self.config["data"].get("test_size", 0.1), seed=42
        )

        self.trainer = SFTTrainer(
            model=self.model,
            args=training_args,
            peft_config=self.peft_config,
            train_dataset=splits["train"],
            eval_dataset=splits["test"],
            callbacks=[MLflowCallback()],
        )

        logger.info(
            f"Starting fine-tuning with strategy '{self.strategy.__class__.__name__}'..."
        )
        self.trainer.train()
        logger.info("Fine-tuning finished.")

    def save_model(self, save_path: str):
        """
        Save the model and tokenizer to the specified path.
        Uses the best model if 'load_best_model_at_end' was enabled.
        """
        if self.trainer is None:
            raise RuntimeError("You must call .tune() before saving the model.")
        logger.info(f"Saving model to {save_path}...")
        self.trainer.save_model(save_path)
        logger.info("Model saved successfully.")

    def evaluate(self) -> Dict[str, float]:
        """
        Evaluate the model on the test dataset.
        """
        if self.trainer is None:
            raise RuntimeError("You must call .tune() before evaluating.")
        logger.info("Evaluating model...")
        return self.trainer.evaluate()
